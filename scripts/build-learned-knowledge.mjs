// Builds the bundled learned pack (RFC_AETHER_KNOWLEDGE_GUARDIAN §10, K8) from knowledge/learned/pack.json.
//
//   node scripts/build-learned-knowledge.mjs --write
//       regenerates src/learned-knowledge.generated.mjs from knowledge/learned/pack.json.
//   node scripts/build-learned-knowledge.mjs --add <export.json> --items <item_id@version,...> --write
//       copies the named items from an Aether export (the learned pack, e.g. GET /api/aether/status
//       learned_pack, saved by the owner) into the pack, with their shadow verdict from <tuning.json>
//       (--tuning, GET /api/tuning), then regenerates. Only items whose shadow verdict is
//       "better_than_active" may be added. A promotion is this change in an owner PR (K9).
// Tests fail when the generated module is stale or an item breaks the rules (learnedItemProblems).
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const PACK_JSON = "knowledge/learned/pack.json";
export const GENERATED_MODULE = "src/learned-knowledge.generated.mjs";
const sha256 = (s) => createHash("sha256").update(s).digest("hex");
const ITEM_FIELDS = ["item_id", "version", "kind", "label", "audience", "situation", "text", "evidence", "provenance", "content_sha256", "proposal_id", "review"];

/** The canonical pack content (items sorted, fields fixed) and its hash. */
export function canonicalPack(pack) {
  const items = [...(pack.items || [])].map((it) => Object.fromEntries(ITEM_FIELDS.filter((k) => it[k] !== undefined).map((k) => [k, it[k]])))
    .sort((a, b) => a.item_id.localeCompare(b.item_id) || a.version - b.version);
  const body = { version: "cryptophys.learned-knowledge.v1", items };
  return { ...body, content_sha256: sha256(JSON.stringify(body)) };
}

export function generatedModule(pack) {
  const p = canonicalPack(pack);
  return `// GENERATED by scripts/build-learned-knowledge.mjs from ${PACK_JSON}. Do not edit by hand.\n` +
    `// The bundled learned pack (RFC_AETHER_KNOWLEDGE_GUARDIAN §10); used only with LEARNED_KNOWLEDGE_ENABLED.\n` +
    `export const LEARNED_PACK = Object.freeze(${JSON.stringify(p, null, 2)});\n`;
}

function main(argv) {
  const arg = (name) => { const i = argv.indexOf(name); return i >= 0 ? argv[i + 1] : null; };
  const packPath = path.join(ROOT, PACK_JSON);
  let pack = JSON.parse(readFileSync(packPath, "utf8"));
  if (arg("--add")) {
    const exported = JSON.parse(readFileSync(arg("--add"), "utf8"));
    const tuning = arg("--tuning") ? JSON.parse(readFileSync(arg("--tuning"), "utf8")) : null;
    const wanted = String(arg("--items") || "").split(",").map((s) => s.trim()).filter(Boolean);
    const source = exported.learned_pack?.items || exported.items || [];
    const verdicts = new Map((tuning?.replays?.knowledge?.candidates || []).map((k) => [`${k.item_id}@${k.item_version}`, k.verdict]));
    for (const key of wanted) {
      const [id, v] = key.split("@");
      const it = source.find((x) => x.item_id === id && String(x.version) === v);
      if (!it) throw new Error(`item ${key} not in the export`);
      const verdict = verdicts.get(key);
      if (!String(verdict || "").startsWith("better_than_active")) throw new Error(`item ${key} has no "better_than_active" shadow verdict (${verdict ?? "none"})`);
      pack.items = [...(pack.items || []).filter((x) => !(x.item_id === id)), { ...it, review: { shadow_verdict: verdict, promoted_on: new Date().toISOString().slice(0, 10) } }];
    }
  }
  const canonical = canonicalPack(pack);
  if (argv.includes("--write")) {
    writeFileSync(packPath, JSON.stringify(canonical, null, 2) + "\n");
    writeFileSync(path.join(ROOT, GENERATED_MODULE), generatedModule(canonical));
    console.log(`learned pack: ${canonical.items.length} items, sha ${canonical.content_sha256}`);
  } else console.log(JSON.stringify({ items: canonical.items.length, content_sha256: canonical.content_sha256 }));
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
