// Builds knowledge-base v4 from knowledge/kb-v4.mjs plus provenance:
// sha256 of every Pine SSOT file it cites and the local-engine identities.
//   node scripts/build-knowledge-base.mjs --write
// writes src/knowledge-base.generated.mjs (bundled into the AI Worker) and
// knowledge-base-v4.json (human-readable copy). Tests fail if either is stale
// or if any cited Pine line no longer contains the quoted text.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { KB_V4_CONTENT, PINE_FILES } from "../knowledge/kb-v4.mjs";
import { computeProvenance } from "./engine-provenance.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const GENERATED_MODULE = "src/knowledge-base.generated.mjs";
export const GENERATED_JSON = "knowledge-base-v4.json";
const sha256 = (data) => createHash("sha256").update(data).digest("hex");

/** Every {file, line, contains} reference in the KB, with its JSON path. */
export function collectRefs(node = KB_V4_CONTENT, at = "$", out = []) {
  if (Array.isArray(node)) node.forEach((v, i) => collectRefs(v, `${at}[${i}]`, out));
  else if (node && typeof node === "object") {
    if (typeof node.file === "string" && Number.isInteger(node.line) && typeof node.contains === "string") out.push({ at, ...node });
    else for (const [k, v] of Object.entries(node)) collectRefs(v, `${at}.${k}`, out);
  }
  return out;
}

/** Returns a list of reference errors (empty when every citation matches the Pine source). */
export function verifyRefs() {
  const lines = Object.fromEntries(Object.entries(PINE_FILES).map(([k, f]) => [k, readFileSync(path.join(ROOT, f), "utf8").split("\n")]));
  return collectRefs().flatMap((r) => {
    const src = lines[r.file];
    if (!src) return [`${r.at}: unknown file key ${r.file}`];
    const text = src[r.line - 1];
    return text !== undefined && text.includes(r.contains) ? [] : [`${r.at}: ${PINE_FILES[r.file]}:${r.line} does not contain ${JSON.stringify(r.contains)}`];
  });
}

export function buildKnowledgeBase() {
  const sources = Object.entries(PINE_FILES).map(([key, file]) => ({ key, path: file, sha256: sha256(readFileSync(path.join(ROOT, file))) }));
  const engines = computeProvenance();
  const content = { ...KB_V4_CONTENT };
  const body = JSON.stringify(content);
  return {
    ...content,
    provenance: {
      generated_by: "scripts/build-knowledge-base.mjs",
      pine_sources: sources,
      local_engine_identities: Object.fromEntries(Object.entries(engines).map(([k, v]) => [k, { source_hash: v.source_hash, implementation_hash: v.implementation_hash }])),
      reference_count: collectRefs().length,
      content_sha256: sha256(body)
    }
  };
}

export function renderModule(kb = buildKnowledgeBase()) {
  return "// GENERATED by scripts/build-knowledge-base.mjs --write. Do not edit by hand.\n" +
    "export const KNOWLEDGE_BASE_V4 = Object.freeze(" + JSON.stringify(kb, null, 2) + ");\n";
}
export const renderJson = (kb = buildKnowledgeBase()) => JSON.stringify(kb, null, 2) + "\n";

if (process.argv.includes("--write")) {
  const errors = verifyRefs();
  if (errors.length) { console.error(errors.join("\n")); process.exit(1); }
  const kb = buildKnowledgeBase();
  writeFileSync(path.join(ROOT, GENERATED_MODULE), renderModule(kb));
  writeFileSync(path.join(ROOT, GENERATED_JSON), renderJson(kb));
  console.log(`wrote ${GENERATED_MODULE} and ${GENERATED_JSON} (${kb.provenance.reference_count} verified Pine references)`);
}
